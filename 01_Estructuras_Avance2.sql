    BEGIN
        EXECUTE IMMEDIATE 'DROP TABLE ' || p_nombre || ' CASCADE CONSTRAINTS PURGE';
        DBMS_OUTPUT.PUT_LINE('Tabla ' || p_nombre || ' eliminada.');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -942 THEN RAISE; END IF;
    END;

