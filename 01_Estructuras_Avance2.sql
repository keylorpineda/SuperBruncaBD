    PROCEDURE borrar_mv(p_nombre IN VARCHAR2) IS
    BEGIN
        EXECUTE IMMEDIATE 'DROP MATERIALIZED VIEW ' || p_nombre;
        DBMS_OUTPUT.PUT_LINE('Vista materializada ' || p_nombre || ' eliminada.');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE != -12003 THEN RAISE; END IF;
    END;

